//! Import generated Rustdoc as mdBook static assets and native navigation.

use std::{
    fs, io,
    path::{Component, Path, PathBuf},
    process::{Command, Stdio},
};

use mdbook_preprocessor::{
    book::Book,
    config::{Config, HtmlConfig},
};
use mdbook_renderer::{RenderContext, Renderer};
use serde::Deserialize;
use sha2::{Digest, Sha256};

const DIRECTORY: &str = "rustdocs";
const MARKER: &str = ".habeas-rustdocs-owner";
const MARKER_CONTENT: &str = "Generated by habeas mdbook. Rustdoc import cache.\n";

#[derive(Deserialize)]
struct Import {
    path: PathBuf,
    #[serde(rename = "crate")]
    crate_name: String,
    #[serde(default, rename = "build-workspace")]
    build_workspace: bool,
}

/// Prepare the Rustdoc static assets before mdBook's HTML renderer copies them.
pub fn preprocess(book: &mut Book, root: &Path, config: &Config) -> io::Result<()> {
    let chapters = book
        .chapters()
        .filter(|chapter| is_entry(&chapter.content))
        .count();
    let import = config
        .get::<Import>("preprocessor.habeas.rustdocs")
        .map_err(|error| io::Error::other(format!("invalid Rustdoc configuration: {error}")))?;
    let Some(import) = import else {
        return if chapters == 0 {
            Ok(())
        } else {
            Err(io::Error::other(
                "the {rustdocs} chapter requires [preprocessor.habeas.rustdocs] configuration",
            ))
        };
    };
    if import.path.is_absolute()
        || import.crate_name.is_empty()
        || !import
            .crate_name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
    {
        return Err(io::Error::other(
            "Rustdoc path must be relative to the project root and crate must name a Rust crate",
        ));
    }
    if import.build_workspace {
        if !import.path.ends_with("doc") {
            return Err(io::Error::other(
                "building workspace Rustdoc requires a path ending in doc",
            ));
        }
        let target = root.join(&import.path);
        let status = Command::new("cargo")
            .current_dir(root)
            .args([
                "doc",
                "--locked",
                "--workspace",
                "--no-deps",
                "--target-dir",
            ])
            .arg(target.parent().expect("doc has a parent directory"))
            .stdin(Stdio::null())
            // mdBook reads the preprocessed book as JSON from our stdout.
            .stdout(Stdio::from(io::stderr()))
            .status()
            .map_err(|error| diagnostic("run cargo doc in", root, error))?;
        if !status.success() {
            return Err(io::Error::other(format!("cargo doc failed with {status}")));
        }
    }
    let source = root
        .join(&import.path)
        .canonicalize()
        .map_err(|error| diagnostic("read Rustdoc directory", &root.join(&import.path), error))?;
    if !source.is_dir() {
        return Err(io::Error::other(format!(
            "Rustdoc import directory {} is not a directory",
            source.display()
        )));
    }
    let landing = PathBuf::from(&import.crate_name).join("index.html");
    let page = source.join(&landing);
    if !page.is_file() {
        return Err(io::Error::other(format!(
            "cannot read Rustdoc crate landing page {}",
            page.display()
        )));
    }

    let files = site_files(&source)?;
    if files
        .iter()
        .any(|file| file.extension().is_some_and(|extension| extension == "md"))
        && !config.contains_key("output.habeas")
    {
        return Err(io::Error::other(
            "Rustdoc includes Markdown assets; configure [output.habeas] command = \"habeas mdbook render\" to publish the complete site",
        ));
    }
    let destination = root.join(&config.book.src).join(DIRECTORY);
    let source_dir = destination
        .parent()
        .expect("the Rustdoc directory has a source directory parent");
    fs::create_dir_all(source_dir)
        .map_err(|error| diagnostic("create book source directory", source_dir, error))?;
    let source_dir = source_dir
        .canonicalize()
        .map_err(|error| diagnostic("read book source directory", source_dir, error))?;
    let destination = source_dir.join(DIRECTORY);
    if source.starts_with(&destination) || destination.starts_with(&source) {
        return Err(io::Error::other(
            "Rustdoc import source and book asset destination must not contain each other",
        ));
    }
    let mut outputs = Vec::new();
    for chapter in book.chapters() {
        if is_entry(&chapter.content) {
            continue;
        }
        if let Some(path) = &chapter.path {
            outputs.push((path.with_extension("html"), "chapter"));
        }
    }
    let html = config
        .get::<HtmlConfig>("output.habeas.html")
        .map_err(|error| io::Error::other(format!("invalid HTML configuration: {error}")))?
        .or(config
            .get::<HtmlConfig>("output.html")
            .map_err(|error| io::Error::other(format!("invalid HTML configuration: {error}")))?)
        .unwrap_or_default();
    for path in html.redirect.keys() {
        outputs.push((
            PathBuf::from(path.split('#').next().unwrap().trim_start_matches('/')),
            "redirect",
        ));
    }
    for path in html.additional_js.iter().chain(&html.additional_css) {
        let mut output = path.clone();
        if html.hash_files {
            let filename = path.to_string_lossy();
            if let Some((name, suffix)) = filename.split_once('.')
                && !name.is_empty()
                && !suffix.is_empty()
            {
                let input = root.join(path);
                let contents = fs::read(&input)
                    .map_err(|error| diagnostic("read configured book asset", &input, error))?;
                let hash = Sha256::digest(contents)[..4]
                    .iter()
                    .map(|byte| format!("{byte:02x}"))
                    .collect::<String>();
                output = PathBuf::from(format!("{name}-{hash}.{suffix}"));
            }
        }
        outputs.push((output, "asset"));
    }
    for (output, kind) in outputs {
        let output = normalize(&output);
        if files.iter().any(|file| {
            let imported = Path::new(DIRECTORY).join(file);
            output == imported || output.starts_with(&imported) || imported.starts_with(&output)
        }) {
            return Err(io::Error::other(format!(
                "Rustdoc import would overwrite book {kind} {}",
                output.display()
            )));
        }
    }
    if destination.exists() {
        let metadata = fs::symlink_metadata(&destination)
            .map_err(|error| diagnostic("inspect book asset directory", &destination, error))?;
        if !metadata.is_dir()
            || fs::read_to_string(destination.join(MARKER)).ok().as_deref() != Some(MARKER_CONTENT)
        {
            return Err(io::Error::other(format!(
                "Rustdoc import would overwrite existing book assets at {}",
                destination.display()
            )));
        }
    }
    if files.iter().any(|path| path == Path::new(MARKER)) {
        return Err(io::Error::other(
            "Rustdoc site conflicts with the import cache's ownership marker",
        ));
    }

    // Stage the complete site before replacing the previous generated cache.
    let stage = tempfile::Builder::new()
        .prefix(".habeas-rustdocs-")
        .tempdir_in(&source_dir)
        .map_err(|error| diagnostic("stage Rustdoc import", &source_dir, error))?;
    for file in files {
        let input = source.join(&file);
        let output = stage.path().join(&file);
        fs::create_dir_all(output.parent().expect("site file has a parent"))
            .map_err(|error| diagnostic("create Rustdoc asset directory", &output, error))?;
        fs::copy(&input, &output)
            .map_err(|error| diagnostic("import Rustdoc file", &input, error))?;
    }
    fs::write(stage.path().join(MARKER), MARKER_CONTENT)
        .map_err(|error| diagnostic("mark generated Rustdoc cache", stage.path(), error))?;
    // Keep the generated cache out of consumer repositories' source tracking.
    let ignore = stage.path().join(".gitignore");
    let mut patterns = fs::read_to_string(&ignore).unwrap_or_default();
    patterns.push_str("\n*\n");
    fs::write(&ignore, patterns)
        .map_err(|error| diagnostic("exclude generated Rustdoc cache", &ignore, error))?;
    if destination.exists() {
        fs::remove_dir_all(&destination)
            .map_err(|error| diagnostic("replace generated Rustdoc cache", &destination, error))?;
    }
    fs::rename(stage.path(), &destination)
        .map_err(|error| diagnostic("install Rustdoc import", &destination, error))?;

    let entry = Path::new(DIRECTORY).join(landing);
    book.for_each_chapter_mut(|chapter| {
        if is_entry(&chapter.content) {
            chapter.path = Some(entry.clone());
            chapter.source_path = None;
            chapter.content.clear();
        }
    });
    Ok(())
}

/// Render the book with mdBook's HTML renderer, then finish the native-site copy.
pub fn render(mut context: RenderContext) -> mdbook_renderer::errors::Result<()> {
    if let Some(html) = context
        .config
        .get::<serde_json::Value>("output.habeas.html")?
    {
        context.config.set("output.html", html)?;
    }
    mdbook_html::HtmlHandlebars::new().render(&context)?;
    if context.config.contains_key("preprocessor.habeas.rustdocs") {
        let source = context.source_dir().join(DIRECTORY);
        for file in site_files(&source)? {
            if file == Path::new(MARKER) || file == Path::new(".gitignore") {
                continue;
            }
            let input = source.join(&file);
            let output = context.destination.join(DIRECTORY).join(&file);
            fs::create_dir_all(output.parent().expect("site file has a parent"))
                .map_err(|error| diagnostic("create Rustdoc output directory", &output, error))?;
            fs::copy(&input, &output)
                .map_err(|error| diagnostic("publish Rustdoc file", &input, error))?;
        }
    }
    Ok(())
}

fn is_entry(content: &str) -> bool {
    let lines = content.lines().collect::<Vec<_>>();
    let Some(start) = lines.iter().position(|line| !line.trim().is_empty()) else {
        return false;
    };
    let end = lines
        .iter()
        .rposition(|line| !line.trim().is_empty())
        .unwrap()
        + 1;
    let lines = &lines[start..end];
    let Some(first) = lines.first() else {
        return false;
    };
    let Some((suffix, length)) = crate::colon_fence(first.trim_end()) else {
        return false;
    };
    suffix == "{rustdocs}"
        && lines.len() >= 2
        && lines[1..lines.len() - 1]
            .iter()
            .all(|line| line.trim().is_empty())
        && crate::colon_fence(lines[lines.len() - 1].trim_end())
            .is_some_and(|(suffix, closing)| suffix.is_empty() && closing >= length)
}

fn site_files(root: &Path) -> io::Result<Vec<PathBuf>> {
    let mut pending = vec![root.to_path_buf()];
    let mut files = Vec::new();
    while let Some(directory) = pending.pop() {
        for entry in fs::read_dir(&directory)
            .map_err(|error| diagnostic("read Rustdoc site directory", &directory, error))?
        {
            let entry =
                entry.map_err(|error| diagnostic("read Rustdoc site entry", &directory, error))?;
            let path = entry.path();
            let kind = entry
                .file_type()
                .map_err(|error| diagnostic("inspect Rustdoc site file", &path, error))?;
            if kind.is_dir() {
                pending.push(path);
            } else if kind.is_file() {
                let relative = path
                    .strip_prefix(root)
                    .expect("site files are below their root");
                files.push(relative.to_path_buf());
            } else {
                return Err(io::Error::other(format!(
                    "cannot import Rustdoc site entry {}: not a regular file or directory",
                    path.display()
                )));
            }
        }
    }
    files.sort();
    Ok(files)
}

fn normalize(path: &Path) -> PathBuf {
    let mut result = PathBuf::new();
    for component in path.components() {
        match component {
            Component::ParentDir => {
                result.pop();
            }
            Component::Normal(segment) => result.push(segment),
            _ => {}
        }
    }
    result
}

fn diagnostic(action: &str, path: &Path, error: io::Error) -> io::Error {
    io::Error::new(
        error.kind(),
        format!("cannot {action} {}: {error}", path.display()),
    )
}
